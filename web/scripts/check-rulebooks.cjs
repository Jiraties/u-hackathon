assert.throws(()=>allocatePreview([one],[applicant('a',80,['unknown'])]));
const { renderToStaticMarkup } = webRequire('react-dom/server');
const React = webRequire('react');
const { UniversityPage } = require('../src/pages/UniversityPage.tsx');
const home = renderToStaticMarkup(React.createElement(UniversityPage,{data:demoData,controller:{workspace:{schema:1,rulebooks:demoData.rulebooks,runs:[]},message:'',saveRule(){},saveRun(){}}}));
assert.ok(home.includes('Set the rules. Make them checkable.'));
assert.ok(home.includes('Create rulebook'));
assert.ok(home.includes('Issue admission tokens'));
assert.ok(!home.includes('Confirmed on-chain'));
(async()=>{
  globalThis.crypto ??= require('node:crypto').webcrypto;
  const prepared=await sealPreviewRulebook(draft,'2026-10-16T02:00:00Z');
  const initial={schema:1,rulebooks:demoData.rulebooks,runs:[]};
  const withDraft=saveRulebookVersion(initial,draft);
  const withSealed=saveRulebookVersion(withDraft,prepared);
  assert.equal(withSealed.rulebooks.find(r=>r.id===prepared.id).status,'preview');
  assert.throws(()=>saveRulebookVersion(withSealed,{...prepared,capacity:33}),/immutable/);
  assert.throws(()=>saveRulebookVersion(withSealed,{...draft,id:'duplicate-version'}),/already exists/);
  assert.equal(initial.rulebooks.some(r=>r.id===draft.id),false);
  assert.equal(prepared.status,'preview'); assert.equal(prepared.publication,null); assert.equal(prepared.chainReference,null);
  assert.match(prepared.commitment,/^0x[0-9a-f]{64}$/);
  assert.equal(prepared.commitment,await rulebookCommitment(draft));
  const expected='0x'+require('node:crypto').createHash('sha256').update(canonicalRulebook(draft)).digest('hex');
  assert.equal(prepared.commitment,expected);
  assert.notEqual(prepared.commitment,await rulebookCommitment({...draft,capacity:31}));
  assert.notEqual(prepared.commitment,await rulebookCommitment({...draft,round:'Round 2'}));
  assert.notEqual(prepared.commitment,await rulebookCommitment({...draft,qualifications:[{field:'curriculum',equals:'Arts–Languages'}]}));
  await assert.rejects(sealPreviewRulebook(prepared,'2026-10-16T03:00:00Z'));
  const refs=nonAdmittedWallet.admission.result.rankedPrograms;
  const rules=refs.map(choice=>choice.programId===prepared.programId?prepared:demoData.rulebooks.find(r=>r.id===choice.rulebookId));
  const run=runAdmissionPreview(rules,{id:nonAdmittedWallet.student.id,scores,preferences:refs.map(c=>c.programId),qualifications:{curriculum:'Science–Mathematics'}},'2026-10-16T03:00:00Z');
  assert.equal(run.applicants,145); assert.equal(run.studentAdmitted,false);
  assert.equal(run.choices.find(c=>c.programId===prepared.programId).rulebookId,prepared.id);
  assert.equal(refs.find(c=>c.programId===prepared.programId).rulebookVersion,1);
  for(const rule of rules) assert.ok(Object.values(run.assignments).filter(id=>id===rule.programId).length<=rule.capacity);
  global.window={location:{search:'?demo=not-admitted'}};
  const { WalletPage }=require('../src/pages/WalletPage.tsx');
  const previewWallet={...nonAdmittedWallet,admission:{status:'not_admitted',result:{...nonAdmittedWallet.admission.result,rankedPrograms:run.choices}}};
  const connectedData={...demoData,rulebooks:[...demoData.rulebooks,prepared],demoWallets:[demoData.wallet,previewWallet]};
  const connected=renderToStaticMarkup(React.createElement(WalletPage,{data:connectedData}));
  assert.ok(connected.includes('59.98'));
  const later=forkRulebook(prepared,connectedData.rulebooks,'2026-10-17T00:00:00Z');
  later.components=[{...later.components[0],weightPercent:100}]; later.requiredSubjects=['tgat'];
  const afterLater=renderToStaticMarkup(React.createElement(WalletPage,{data:{...connectedData,rulebooks:[...connectedData.rulebooks,later]}}));
  assert.equal(connected,afterLater);
  const missing=renderToStaticMarkup(React.createElement(WalletPage,{data:{...connectedData,rulebooks:connectedData.rulebooks.filter(r=>r.id!==run.choices[0].rulebookId)}}));
  assert.ok(missing.includes('historical result is unavailable'));
  delete global.window;
  assert.equal(ruleIsOnChain(prepared),false);
  console.log('Rulebook checks passed: validation, scales, eligibility, canonical hashes, historical versions, capacity, ties and preference matching.');
})().catch(error=>{console.error(error);process.exitCode=1;});
