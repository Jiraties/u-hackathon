require('./check-admission-results.cjs');
const assert = require('node:assert/strict');
const { createRequire } = require('node:module');
const path = require('node:path');
const webRequire = createRequire(path.resolve(__dirname,'../package.json'));
const { demoData,nonAdmittedWallet } = require('../src/data/demo.ts');
const { validateRulebook,canonicalRulebook,rulebookCommitment,evaluateRulebook,forkRulebook,ruleIsOnChain } = require('../src/domain/rulebooks.ts');
const { sealPreviewRulebook,saveRulebookVersion,allocatePreview,runAdmissionPreview } = require('../src/services/ruleWorkspace.ts');
const base = demoData.rulebooks.find(r=>r.programId==='computer-engineering-2027');
const scores = nonAdmittedWallet.scores;
assert.deepEqual(validateRulebook(base),[]);
assert.equal(evaluateRulebook(base,scores).total,59.8);
assert.equal(evaluateRulebook(base,scores).rawTotal,evaluateRulebook({...base,components:[...base.components].reverse()},scores).rawTotal);
assert.equal(evaluateRulebook(base,scores).eligible,true);
assert.ok(validateRulebook({...base,capacity:0}).length);
assert.ok(validateRulebook({...base,capacity:1.5}).length);
assert.ok(validateRulebook({...base,components:[...base.components,base.components[0]]}).length);
assert.ok(validateRulebook({...base,components:base.components.map(c=>({...c,weightPercent:20}))}).length);
assert.ok(validateRulebook({...base,requiredSubjects:['unknown']}).length);
assert.equal(evaluateRulebook(base,scores.slice(1)).status,'unavailable');
assert.equal(evaluateRulebook(base,scores.map(s=>s.id==='tgat'?{...s,maximum:200}:s)).status,'unavailable');
assert.equal(evaluateRulebook({...base,components:base.components.map(c=>({...c,minimumPercent:99}))},scores).eligible,false);
assert.equal(evaluateRulebook({...base,qualifications:[{field:'curriculum',equals:'Science–Mathematics'}]},scores).eligible,false);
assert.equal(evaluateRulebook({...base,qualifications:[{field:'curriculum',equals:'Science–Mathematics'}]},scores,{curriculum:'Science–Mathematics'}).eligible,true);
assert.equal(canonicalRulebook(base),canonicalRulebook({...base,components:[...base.components].reverse(),requiredSubjects:[...base.requiredSubjects].reverse()}));
const gpax={...base,components:[{scoreId:'gpax',label:'GPAX',source:'demo-school-record',sourceComponentId:'GPAX',maximum:4,transformation:'normalize-to-100',weightPercent:100,minimumPercent:75}],requiredSubjects:['gpax']};
assert.equal(evaluateRulebook(gpax,[{id:'gpax',score:3.2,maximum:4,subject:'GPAX',label:'GPAX',provenance:'simulated-exam-provider'}]).total,80);
const draft=forkRulebook(base,demoData.rulebooks,'2026-10-16T01:00:00Z');
assert.equal(draft.version,2); assert.equal(draft.status,'draft'); assert.equal(draft.commitment,null);
draft.components[0].weightPercent=25; draft.components[1].weightPercent=25;
assert.equal(base.components[0].weightPercent,20);
assert.equal(evaluateRulebook(base,scores).total,59.8);
assert.equal(evaluateRulebook(base,scores).rawTotal,evaluateRulebook({...base,components:[...base.components].reverse()},scores).rawTotal);
assert.equal(evaluateRulebook(draft,scores).total,59.98);
assert.equal(ruleIsOnChain(base),false);
assert.equal(ruleIsOnChain({...base,status:'published'}),false);
