const two={...one,id:'two-v1',programId:'two'};
const applicant=(id,score,preferences)=>({id,scores:[{...scores[0],score}],preferences,qualifications:{}});
const applicants=[applicant('a',80,['one','two']),applicant('b',90,['one']),applicant('c',85,['two'])];
assert.deepEqual(allocatePreview([one,two],applicants),{a:null,b:'one',c:'two'});
assert.equal(allocatePreview([one],[applicant('z',80,['one']),applicant('a',80,['one'])]).a,'one');
assert.deepEqual(allocatePreview([one,two],applicants),allocatePreview([one,two],[...applicants].reverse()));
